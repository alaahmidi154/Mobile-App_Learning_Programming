-- =====================================================
-- schema_seed_pg.sql  (PostgreSQL 16)
-- Tables : Utilisateur, Mission, Test, Soumission
-- Noms entre guillemets, en PascalCase : c'est ce que EF Core
-- attend par defaut (classe Utilisateur -> table "Utilisateur",
-- propriete XpTotal -> colonne "XpTotal").
-- Rejouable : sert aussi de reset pour la demo.
-- Les comptes demo se creent via /api/auth/register (hash BCrypt).
-- =====================================================

DROP TABLE IF EXISTS "Soumission" CASCADE;
DROP TABLE IF EXISTS "Test" CASCADE;
DROP TABLE IF EXISTS "Mission" CASCADE;
DROP TABLE IF EXISTS "Utilisateur" CASCADE;

CREATE TABLE "Utilisateur" (
    "Id"              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Nom"             VARCHAR(100) NOT NULL,
    "Email"           VARCHAR(200) NOT NULL UNIQUE,
    "MotDePasseHache" VARCHAR(200) NOT NULL,
    "XpTotal"         INT          NOT NULL DEFAULT 0,
    "NiveauJoueur"    INT          NOT NULL DEFAULT 1,
    "Role"            VARCHAR(20)  NOT NULL DEFAULT 'joueur'
        CHECK ("Role" IN ('joueur', 'admin'))
);

CREATE TABLE "Mission" (
    "Id"          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Titre"       VARCHAR(150) NOT NULL,
    "Enonce"      TEXT         NOT NULL,
    "Difficulte"  VARCHAR(20)  NOT NULL
        CHECK ("Difficulte" IN ('Débutant', 'Intermédiaire', 'Avancé')),
    "Xp"          INT          NOT NULL,
    "CodeDepart"  TEXT         NOT NULL
);

CREATE TABLE "Test" (
    "Id"             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "IdMission"      INT     NOT NULL REFERENCES "Mission"("Id") ON DELETE CASCADE,
    "Entree"         TEXT    NOT NULL,   -- valeurs separees par des retours a la ligne
    "SortieAttendue" TEXT    NOT NULL,
    "Visible"        BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE "Soumission" (
    "Id"             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "IdUtilisateur"  INT         NOT NULL REFERENCES "Utilisateur"("Id"),
    "IdMission"      INT         NOT NULL REFERENCES "Mission"("Id"),
    "Code"           TEXT        NOT NULL,
    "Verdict"        VARCHAR(20) NOT NULL
        CHECK ("Verdict" IN ('réussi', 'échoué', 'erreur', 'temps dépassé')),
    "TempsExecution" INT         NOT NULL DEFAULT 0,   -- en ms
    "Date"           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX "IX_Test_Mission"    ON "Test"("IdMission");
CREATE INDEX "IX_Soumission_User" ON "Soumission"("IdUtilisateur", "IdMission", "Verdict");
CREATE INDEX "IX_Utilisateur_Xp"  ON "Utilisateur"("XpTotal" DESC);

